class ProviderModel {
  final String name;
  final String role;
  final String email;
  final String phone;
  final String rating;
  final String reviews;
  final String location;
  final String profileImage;
  final String jobsDone;

  ProviderModel({
    required this.name,
    required this.role,
    required this.email,
    required this.phone,
    required this.rating,
    required this.reviews,
    required this.location,
    required this.profileImage,
    required this.jobsDone,
  });
}
